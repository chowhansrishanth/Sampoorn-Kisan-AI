// Fast lookup structures
const LOWERCASE_MAPS = {};
const SORTED_KEYS_CACHE = {};

// Initialize lowercase cache for high-speed matching
for (const [phrase, translations] of Object.entries(PHRASE_DICTIONARY)) {
  const lowerPhrase = phrase.toLowerCase();
  for (const [lang, trans] of Object.entries(translations)) {
    if (!LOWERCASE_MAPS[lang]) LOWERCASE_MAPS[lang] = new Map();
    LOWERCASE_MAPS[lang].set(lowerPhrase, trans);
  }
}

/**
 * Fast translation lookup for a phrase
 */
export function lookupTranslation(phrase, langCode) {
  if (!phrase || langCode === "EN" || !SUPPORTED_LANGUAGES[langCode]) {
    return null;
  }

  // 1. Direct match
  const direct = PHRASE_DICTIONARY[phrase];
  if (direct && direct[langCode]) {
    return direct[langCode];
  }

  // 2. Trimmed match
  const trimmed = phrase.trim();
  const trimmedMatch = PHRASE_DICTIONARY[trimmed];
  if (trimmedMatch && trimmedMatch[langCode]) {
    return trimmedMatch[langCode];
  }

  // 3. Lowercase match
  const lowerMap = LOWERCASE_MAPS[langCode];
  if (lowerMap && lowerMap.has(trimmed.toLowerCase())) {
    return lowerMap.get(trimmed.toLowerCase());
  }

  // 4. Pattern matches (e.g., "Day 45", "Day 0 (Sowing)")
  const dayMatch = trimmed.match(/^Day\s+(\d+)(\s*\(.*?\))?$/i);
  if (dayMatch) {
    const num = dayMatch[1];
    const paren = dayMatch[2] ? dayMatch[2].trim() : "";
    const dayWord = {
      HI: "दिन",
      TE: "రోజు",
      TA: "நாள்",
      KN: "ದಿನ",
      MR: "दिवस",
      PA: "ਦਿਨ",
      BN: "দিন",
      GU: "દિવસ"
    }[langCode] || "Day";

    let translatedParen = "";
    if (paren) {
      const inner = paren.replace(/^\(/, "").replace(/\)$/, "").trim();
      const innerTrans = lookupTranslation(inner, langCode);
      translatedParen = ` (${innerTrans || inner})`;
    }
    return `${dayWord} ${num}${translatedParen}`;
  }

  return null;
}

/**
 * Translates compound text with partial phrase replacement
 */
export function translateCompoundText(text, langCode) {
  if (!text || langCode === "EN" || !SUPPORTED_LANGUAGES[langCode]) {
    return text;
  }

  const direct = lookupTranslation(text, langCode);
  if (direct) return direct;

  // Cache sorted keys by length descending for greedy substring matching
  if (!SORTED_KEYS_CACHE[langCode]) {
    SORTED_KEYS_CACHE[langCode] = Object.keys(PHRASE_DICTIONARY)
      .filter((k) => PHRASE_DICTIONARY[k][langCode] && k.length > 3)
      .sort((a, b) => b.length - a.length);
  }

  let result = text;
  const keys = SORTED_KEYS_CACHE[langCode];
  
  // Replace up to 10 prominent substrings
  let replacements = 0;
  for (let i = 0; i < keys.length && replacements < 10; i++) {
    const key = keys[i];
    if (result.includes(key)) {
      result = result.split(key).join(PHRASE_DICTIONARY[key][langCode]);
      replacements++;
    }
  }

  return result;
}
